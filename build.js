// Dependency-free build. Classic scripts work over file:// and on GitHub Pages.
import {readFile,writeFile} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import path from 'node:path';
const root=path.dirname(fileURLToPath(import.meta.url));
const sources=await Promise.all(['core.js','docx.js','app.js'].map(async file=>{
  const source=await readFile(path.join(root,file),'utf8');
  const plain=source.replace(/^import\s+.*?from\s+['"].*?['"];?\s*$/gm,'').replace(/^export\s+(?=(?:async\s+)?function|const|let|class)/gm,'');
  if(/^\s*(import|export)\s/m.test(plain))throw new Error(`Unsupported module declaration: ${file}`);
  return `// Source: ${file}\n${plain}`;
}));
const bundle=`/* Generated by node build.js. Edit source files instead. */\n(function(){\n'use strict';\n${sources.join('\n')}\n})();\n`;
await writeFile(path.join(root,'app.bundle.js'),bundle);
const [html,css,extraCss,zip]=await Promise.all(['index.html','styles.css','enhancements.css','vendor/jszip.min.js'].map(file=>readFile(path.join(root,file),'utf8')));
// Inline all operational assets; Google Fonts is optional and uses installed-font fallbacks.
const safeScript=text=>text.replace(/<\/script/gi,'<\\/script');
const standalone=html.replace('<link rel="stylesheet" href="styles.css">',`<style>${css}\n${extraCss}</style>`).replace('<link rel="stylesheet" href="enhancements.css">','').replace('<script src="vendor/jszip.min.js"></script><script src="app.bundle.js"></script>',()=>`<script>${safeScript(zip)}</script><script>${safeScript(bundle)}</script>`);
if(standalone.includes('src="app.bundle.js"'))throw new Error('Standalone script replacement failed');
await writeFile(path.join(root,'standalone.html'),standalone);
console.log('Ready: index.html (folder) and standalone.html (single file)');
